import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import type { ChangedFile } from "../lib/git.ts";
import {
  type AttributionTerms,
  attributionMatches,
  changedLineCoverage,
  commitMessageBody,
  handbookViolations,
  isExempt,
  manualCheckViolations,
  parseMiseTools,
  parseVersions,
  testGuardViolations,
  versionsViolations,
} from "../lib/guards.ts";

const terms = JSON.parse(
  readFileSync("scripts/kit/attribution-terms.json", "utf8"),
) as AttributionTerms;

describe("attribution guard", () => {
  it.each([
    "Co-Authored-By: Claude Opus <noreply@anthropic.com>",
    "co-authored-by: someone <a@b.c>",
    "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
    "Generated by Codex",
    "This file was ai-generated",
    "Written with an AI assistant",
    "Ported with help from Copilot",
    "Gemini suggested this",
  ])("flags %s", (text) => {
    expect(attributionMatches(text, terms)).toHaveLength(1);
  });

  it.each([
    "feat(entitlements): add public plan catalog",
    "openapi.json is generated by scripts/openapi.ts",
    "Use cursor pagination for lists",
    "Paid tiers include more seats",
  ])("allows %s", (text) => {
    expect(attributionMatches(text, terms)).toEqual([]);
  });

  it("drops git comment lines from commit message files", () => {
    expect(commitMessageBody("feat: x\n# Please enter the commit message\nbody")).toBe(
      "feat: x\nbody",
    );
  });

  it("exempts the instruction files but not product code", () => {
    expect(isExempt("AGENTS.md", terms)).toBe(true);
    expect(isExempt(".claude/settings.json", terms)).toBe(true);
    expect(isExempt("src/modules/a.ts", terms)).toBe(false);
    expect(isExempt("docs/HANDBOOK.md", terms)).toBe(false);
  });
});

describe("test guard", () => {
  const removed = new Map<string, string[]>([
    ["src/a.test.ts", ["    expect(plan.key).toBe('free');"]],
    ["src/b.test.ts", ["  // a comment", "  const x = 1;"]],
  ]);
  const lookup = (f: ChangedFile): string[] => removed.get(f.path) ?? [];

  it("flags deleted, moved and assertion-changed test files", () => {
    const changes: ChangedFile[] = [
      { status: "D", path: "src/gone.test.ts" },
      { status: "R", oldPath: "src/old.test.ts", path: "src/new.test.ts" },
      { status: "M", path: "src/a.test.ts" },
      { status: "M", path: "src/b.test.ts" },
      { status: "D", path: "src/not-a-test.ts" },
    ];
    expect(testGuardViolations(changes, lookup, new Set())).toEqual([
      "src/gone.test.ts: existing test file deleted or moved",
      "src/old.test.ts: existing test file deleted or moved",
      "src/a.test.ts: assertion removed or changed: expect(plan.key).toBe('free');",
    ]);
  });

  it("allows changes to test files the item lists by exact path", () => {
    const changes: ChangedFile[] = [{ status: "M", path: "src/a.test.ts" }];
    expect(testGuardViolations(changes, lookup, new Set(["src/a.test.ts"]))).toEqual([]);
  });
});

describe("handbook gate", () => {
  const handbook =
    "### Module: health\nSee `src/modules/health/index.ts:12` and `docs/SPEC.md`.\nIgnore `modules/<name>/`, `pnpm check` and `src/**`.\nMissing `src/gone.ts`.";
  const exists = (p: string): boolean => p !== "src/gone.ts";

  it("requires a section per module and existing referenced paths", () => {
    expect(handbookViolations(handbook, ["health", "entitlements"], exists)).toEqual([
      'module "entitlements" has no "### Module: entitlements" section in HANDBOOK chapter 5',
      "HANDBOOK references a path that does not exist: src/gone.ts",
    ]);
  });
});

describe("versions gate", () => {
  const lines = parseVersions(
    "- `vitest` — MIT — x — https://v — 2026\n- `@vitest/coverage-v8` — MIT — x — u — d\n- `node` — MIT — r — u — d\n- `zod` 4.6.7 — MIT — planned — u — d\n- `@types/node` — MIT — t — u — d\n",
  );
  const tools = parseMiseTools(
    '[tools]\nnode = "26.13.1"\n"github:opengrep/opengrep" = "2.0.0"\n[env]\nX = "1"\n',
  );

  it("parses mise tools with backend prefixes", () => {
    expect(tools).toEqual({ node: "26.13.1", opengrep: "2.0.0" });
  });

  it("flags missing lines, ranges, versions on installed lines, split families and @types/node drift", () => {
    const violations = versionsViolations({
      lines,
      dependencies: {
        vitest: "5.1.0",
        "@vitest/coverage-v8": "^5.0.0",
        zod: "4.6.7",
        "@types/node": "24.0.0",
        express: "5.3.0",
      },
      tools,
    });
    expect(violations).toEqual([
      'dependency "@vitest/coverage-v8" is not pinned exactly: "^5.0.0"',
      'VERSIONS line for installed "zod" carries a version; remove it (the package.json pin is the source)',
      'dependency "express" has no line in docs/VERSIONS.md',
      'tool "opengrep" has no line in docs/VERSIONS.md',
      "vitest packages must share one version, found 5.1.0, ^5.0.0",
      "@types/node major 24.0.0 does not match node 26.13.1",
    ]);
  });
});

describe("changed-line coverage", () => {
  const root = "/repo";
  const coverage = {
    "/repo/src/a.ts": {
      statementMap: {
        "0": { start: { line: 1 } },
        "1": { start: { line: 2 } },
        "2": { start: { line: 9 } },
      },
      s: { "0": 1, "1": 0, "2": 0 },
    },
  };

  it("counts only statements on changed lines", () => {
    const changed = new Map([["src/a.ts", new Set([1, 2])]]);
    expect(changedLineCoverage(coverage, changed, root)).toEqual({
      covered: 1,
      total: 2,
      uncovered: ["src/a.ts:2"],
    });
  });

  it("ignores files without coverage data", () => {
    const changed = new Map([["src/types-only.ts", new Set([1])]]);
    expect(changedLineCoverage(coverage, changed, root)).toEqual({
      covered: 0,
      total: 0,
      uncovered: [],
    });
  });
});

describe("PR manual check guard", () => {
  const body = (manual: string) =>
    `Item: P1-01\n\n## What changed\n\nx\n\n## Manual check\n<!-- hint -->\n${manual}\n`;

  it("accepts none, a body without the section, and steps that switch to the branch and back", () => {
    expect(manualCheckViolations(body("none"))).toEqual([]);
    expect(manualCheckViolations("Bumps pino from 10.4.0 to 10.5.0.")).toEqual([]);
    expect(
      manualCheckViolations(
        body(
          "```sh\ngit fetch origin && git switch feat/P1-01-x && git pull\ncurl localhost:3000\ngit switch main\n```",
        ),
      ),
    ).toEqual([]);
  });

  it("rejects an empty section, a missing switch to the branch and a missing switch back", () => {
    expect(manualCheckViolations(body(""))).toEqual([
      'Manual check is empty; write the commands or "none"',
    ]);
    expect(manualCheckViolations(body("curl localhost:3000"))).toEqual([
      "Manual check must start with `git switch <branch>` before any other command",
    ]);
    expect(manualCheckViolations(body("git switch main\ncurl localhost:3000"))).toHaveLength(1);
    expect(manualCheckViolations(body("git switch feat/x\ncurl localhost:3000"))).toEqual([
      "Manual check must end with `git switch main`",
    ]);
  });

  it("ignores a later section after Manual check", () => {
    const text = `${body("none")}\n## Notes\ngit switch other\n`;
    expect(manualCheckViolations(text)).toEqual([]);
  });
});
