/**
 * Writes `.env.example` from the config schema: every key with its default, and required keys
 * without a default left empty.
 * Run with `node scripts/env-example.ts`; a test fails when the file drifts from the schema.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { configSchema } from "#platform/config/schema.ts";

const format = (value: unknown): string => (Array.isArray(value) ? value.join(",") : String(value));

/** The key's default, or an empty string when the key is required. */
function defaultOf(field: z.core.$ZodType): string {
  const parsed = z.safeParse(field, undefined);
  return parsed.success ? format(parsed.data) : "";
}

export function renderEnvExample(schema: z.ZodObject = configSchema): string {
  const lines = Object.entries(schema.shape).map(([key, field]) => `${key}=${defaultOf(field)}`);
  return [
    "# Generated by scripts/env-example.ts from src/platform/config/schema.ts. Do not edit.",
    ...lines,
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(".env.example", renderEnvExample());
  console.log("wrote .env.example");
}
